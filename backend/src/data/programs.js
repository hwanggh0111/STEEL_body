// 그날 가슴에 할 운동 넷이 나온다. 그런데 처음 온 사람이 모르는 것은 「가슴 날에 뭘
// 하나」가 아니라 **「일주일을 어떻게 짜나」**다. 월요일에 가슴을 했으면 화요일엔 뭘
