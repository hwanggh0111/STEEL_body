// 그래서 지금 앱은 **빈 루틴에서 시작한다.** 뭘 넣을지 아는 사람만 쓸 수 있다.
// 경쟁 앱(플랜핏 · 핏부스트)이 돈을 받는 자리가 바로 여기다.
//
// ── 어떻게 쓰나 ──
//
// 프로그램 하나를 고르면 **그 날들이 그대로 「내 루틴」이 된다** — 3분할을 고르면
// 내 루틴 셋이 한 번에 생긴다. 그 다음부터는 평소처럼 고쳐 쓴다. 프로그램은
// **시작점일 뿐**이고, 앱이 붙잡아두지 않는다.
//
// ── 운동 이름은 사전에 있는 것만 쓴다 ──
//
// `frontend/src/data/exerciseDict.js` 에 있는 이름이어야 **자세 설명 단추가 뜬다.**
// 없는 이름을 적으면 그 줄만 조용히 단추가 사라진다 — `npm run api` 가 잡는다.

