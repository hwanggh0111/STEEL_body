// ── 「눈에 보이지 않는 글자」 표는 **한 자리**다 ── (2026-11-19 · 정석)
//
// 11/18 에 `utils/nickname.js` 가 넓은 표(`NICK_INVISIBLE`)를 들고 닉네임을 닫았다.
// 그런데 `utils/sanitize.js` 는 좁은 표(`INVISIBLE` — 제어 문자 · 방향 뒤집기만)를 그대로
// 들고 있었다. **선이 둘이 되어 류가 반만 닫혔다** — 2차에서 전부 밟혔다:
//
//   운동 이름 · 루틴 이름 · 계획 이름 · 체육관 설정 · 목록 글에
//   U+200B ×3 · U+3164 · U+2800 · U+00AD · U+180E · 태그 글자만으로 된 이름이 **통과**했다
//   → 목록에 **이름이 없는 줄**이 생긴다 (닉네임에서 11/18 에 닫은 바로 그 결함이다)
//
// 그리고 꼴 검사(`tagLike`)가 **지우기 전에** 돌아서, 꺾쇠 바로 뒤에 보이지 않는 글자
// 하나를 끼우면 「꺾쇠는 거절한다」는 선을 넘어갔다. 그래서 이 파일을 두고 —
//   · 표는 여기 하나뿐이다 (`sanitize.js` · `nickname.js` 둘이 이것을 쓴다)
//   · 꼴을 보는 손은 **먼저 지우고** 본다
//
// **정규식은 글자를 박아 넣지 않고 `\u` 로 적는다.** U+2028 을 정규식 안에 날글자로
// 두면 JS 가 파일을 못 읽는다(줄 끝으로 본다) — 11/19 에 한 번 밟았다.
//
// 지우는 것 —
//   제어 문자(줄바꿈 · 탭 제외) · U+00AD 줄임 하이픈 · U+061C 아랍 글자 표시
//   U+115F·U+1160·U+3164·U+FFA0 한글 채움 · U+180E 몽골 모음 구분
//   U+200B–U+200F 폭 0 · 방향 표시 · U+202A–U+202E 방향 뒤집기
//   U+2060–U+2064 · U+2066–U+2069 방향 격리 · U+FEFF
//   U+2800 빈 점형 — 브라유지만 이 하나는 눈에 아무것도 없다 (U+2801 이후는 **남긴다**)
//   U+E0000–U+E007F 태그 글자 — 안 보이면서 글을 실어 보낸다
const INVISIBLE_SOURCE =
  '[\\u0000-\\u0008\\u000B\\u000C\\u000E-\\u001F\\u007F\\u00AD\\u061C'
  + '\\u115F\\u1160\\u180E\\u200B-\\u200F\\u202A-\\u202E\\u2060-\\u2064'
  + '\\u2066-\\u2069\\u2800\\u3164\\uFEFF\\uFFA0]'
  + '|[\\u{E0000}-\\u{E007F}]';

/** 새 정규식을 만들어 준다 — `g` 를 가진 것을 돌려쓰면 `lastIndex` 가 남는다 */
function invisibleRe() {
  return new RegExp(INVISIBLE_SOURCE, 'gu');
}

/** 보이지 않는 글자를 걷어낸다. **꼴을 보기 전에** 이것을 통과시킨다 */
function stripInvisible(str) {
  if (typeof str !== 'string') return '';
  return str.replace(invisibleRe(), '');
}

module.exports = { INVISIBLE_SOURCE, invisibleRe, stripInvisible };
