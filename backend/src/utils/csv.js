// CSV 한 칸.
//
// **엑셀은 `=` 로 시작하는 칸을 수식으로 읽는다.** 운동명은 사람이 자유롭게 치는
// 칸이라 `=HYPERLINK("http://나쁜곳","눌러")` 를 운동명으로 저장해두면, 내보낸 파일을
// 엑셀에서 열었을 때 그 자리가 **눌리는 링크**가 된다. `+` · `@` · 탭 · 캐리지리턴으로
// 시작하는 칸도 같다. 새니타이즈는 이걸 못 막는다 — 태그도 아니고 스크립트도 아니라서다.
//
// 앞에 작은따옴표를 붙이면 엑셀이 글자로 읽는다. 파일에는 보이지만 셀에는 안 나온다.
//
// **음수는 그냥 둔다.** `-` 로 시작한다고 다 막으면 유연성의 「앉아 앞으로 굽히기 -5cm」
// 같은 진짜 숫자가 글자가 되어 엑셀에서 합계가 안 된다. 숫자가 아닌 `-1+1` 만 막는다.
const RISKY = /^[=+@\t\r]/;
const PLAIN_NUMBER = /^-?\d+(\.\d+)?$/;

function csvCell(v) {
  let s = String(v ?? '');
  if (RISKY.test(s) || (s.startsWith('-') && !PLAIN_NUMBER.test(s))) s = "'" + s;
  return '"' + s.replace(/"/g, '""') + '"';
}

module.exports = { csvCell };
