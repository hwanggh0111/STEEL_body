// **한 사람이 쥘 수 있는 줄 수 — 한 자리에서 온다** (2026-11-26 · 정석)
//
// ── 왜 생겼나 ──
//
// 11/25 밤에 근호가 측정 · 메모 둘에 상한을 붙였다(「한 사람이 쥘 수 있는 양에 상한이
// 없음」). 그런데 **같은 류가 다섯 자리 더 있었다** — 11/26 전수검사에서 세어보니:
//
//   운동    `POST /workouts`     파일로 넣는 길은 6만 줄에서 막는데 **손으로 적는 길은 무제한**
//   인바디  `POST /inbody`       같다 (파일 길만 6천)
//   계획    `POST /plans`        **하루 10개**만 있고 총량이 없다 → 2년 × 10 = 7,300
//   루틴    `POST /my-routines`  루틴 **안의 운동**은 50개로 막는데 **루틴 개수**는 무제한
//   제보    `POST /reports`      무제한
//
// 왜 이것이 문제인가 — **이 DB 는 파일 하나를 통째로 쓴다.** 한 사람이 불린 양이
// **모두의 저장 시간**이 된다(5년치 29만 줄에서 쓰기 한 번이 수백 ms 다). 서버는
// `--max-old-space-size=256` 으로 돈다. `spamCheck` 는 분당 60 을 막지만 **하루를
// 두면 8만 줄**이고, 막는 자가 어디에도 없었다.
//
// ── 왜 여기 모았나 ──
//
// 11/13 에 가져오기에서 같은 꼴로 한 번 데었다(`importData.js` 머리글): 상한을 **딴 표**에
// 두고 `MAX_TOTAL[kind]` 로 찾아 쓰다가, 갈래를 더하면 `undefined - have` → `NaN` 으로
// **상한 검사가 조용히 사라지는** 길이 열려 있었다. 그래서 그 파일은 상한을 갈래 안으로
// 옮겼다. 지금은 반대 문제다 — **같은 값을 두 길(손으로 적기 · 파일로 넣기)이 각자**
// 들고 있으면, 한쪽을 올리는 날 다른 쪽이 옛 수로 막는다. 사람은 「파일로는 들어가는데
// 손으로는 안 된다」를 겪는다.
//
// 그래서 **값은 여기 한 벌만** 둔다. 파일 길(`importData.js` 의 `KINDS[].max`)도
// 손으로 적는 길도 이것을 든다. `npm run caps` 가 두 길이 같은 수를 보는지 지킨다.
//
// ── 수는 어떻게 정했나 ──
//
// **사람이 못 넘을 만큼 넉넉하게, 그러나 끝이 있게.** 막는 쪽으로 틀면 적은 것을
// 못 담는 사람이 생기므로, 「아주 열심히 쓰는 사람의 5~10년」을 기준으로 잡았다.
const CAPS = {
  // 5년치가 29,200줄(하루 16세트)이다. 10년을 열심히 해도 6만이면 남는다
  workouts: 60000,
  // 하루 한 번 재도 16년. 인바디는 그보다 드물게 잰다
  inbody: 6000,
  // 둘레 아홉 칸 · 1RM 셋 · 체력 여섯이 한 줄씩이라, 하루 한 번씩 재면 2만 줄은 3년 남짓
  measures: 20000,
  // 계획은 앞으로 2년까지 담는다(`isPlanDay`) — 하루 10개 × 730일 = 7,300 이 상한선이고,
  // 거기까지 채우는 것은 계획이 아니라 목록이다. **지난 계획은 지우지 않는다**(못 한 날이
  // 왜 못 했는지 남아야 한다 — `routes/plans.js` 머리글)는 것까지 보고 5,000 으로 둔다
  plans: 5000,
  // 루틴은 사람이 손으로 짜는 것이다. 많이 쓰는 사람도 부위별 · 주기별로 서른 남짓이다
  routines: 300,
  // 제보는 「할 말이 있을 때」 쓴다. 한 사람이 300건을 넘기면 그건 제보가 아니다
  reports: 300,
  // 메모 — 루틴 메모(날짜 없는 것) · 날짜 메모(하루 한 장이라 날 수만큼, 10년 남짓)
  notes: 30,
  dayNotes: 4000,
  // ── 알림을 받는 기기 수 ── (2026-11-26 · 정석)
  //
  // 구독은 **기기마다 하나**다(폰 · PC · 태블릿). 그런데 브라우저를 다시 깔거나
  // 캐시를 비우면 **같은 기기가 새 주소**를 받으므로 줄이 는다 — 즉 사람이 가만히
  // 있어도 늘어나는 칸이다. 그리고 알림을 보낼 때 서버가 **줄마다 직접 POST** 한다
  // (`utils/push.js` 의 `sendToUser`): 줄이 천 개면 알림 한 통이 **천 번 바깥으로**
  // 나간다. 스물이면 사람에게 넉넉하고(기기 다섯 × 브라우저 넷), 넘으면 **가장 오래
  // 안 보인 줄을 밀어낸다** — 막으면 **새 기기가 알림을 못 받는다**(그쪽이 더 나쁘다)
  pushSubs: 20,
};

/**
 * 그 갈래의 상한. **없는 갈래를 물으면 터진다** — 조용히 `undefined` 를 돌려주면
 * 부르는 쪽에서 `length >= undefined` 가 **false** 가 되어 **상한이 사라진다**
 * (11/13 에 가져오기가 바로 그 꼴로 데었다. 모를 때는 우는 쪽으로 틀린다).
 */
function capOf(kind) {
  if (!Object.hasOwn(CAPS, kind)) {
    throw new Error(`[rowCaps] 모르는 갈래: ${kind}`);
  }
  return CAPS[kind];
}

/** 「가득해요」를 **한 말로** 적는다 — 자리마다 따로 적으면 곧 서로 다른 말을 한다 */
function fullWhy(label, kind) {
  return `${label} 기록이 가득해요 (${capOf(kind).toLocaleString()}줄까지) — 안 쓰는 것을 지워주세요`;
}

module.exports = { CAPS, capOf, fullWhy };
