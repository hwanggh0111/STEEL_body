// 욕설 사전에 **멀쩡한 말**이 걸리지 않는가 (2026-10-22).
//
//   npm run words     (npm run check 에도 들어 있다)
//
// ── 왜 ──
//
// 이 사전은 **제보 글에만** 쓰인다(`routes/reports.js`). 걸리면 그 글은 막히고
// 누적이 쌓여 다음 한 번에 1일 정지로 간다. 즉 오탐이 때리는 사람은
// **버그를 알려주러 온 사람**이다.
//
// 그리고 사전은 **글 안에 들어 있으면** 걸리게 돼 있고(우회를 막으려고 그렇게 뒀다),
// 보기 전에 **공백을 지운다.** 그래서 멀쩡한 두 낱말이 붙어 욕이 되는 자리가 생긴다 —
//
//     「오후 3시 발목이 시큰해요」  → 시발목   → severe  (2026-10-22 에 고쳤다)
//     「4시 팔꿈치가 아파요」       → ㅅ시팔…  → severe  (숫자 4 가 ㅅ 으로도 바뀐다)
//     「미니미 라는 닉네임」        → 니미     → severe  (홀로 선 '니미' 를 뺐다)
//
// **눈으로 볼 수 없다.** 사전에 낱말 백여 개가 있고 글은 무엇이든 올 수 있다.
// 그래서 **헬스장에서 쓰는 말을 수천 개 만들어** 들이민다. 그리고 반대쪽도 본다 —
// 오탐을 줄이려고 사전을 깎다가 **진짜 욕을 놓치면** 그게 더 나쁘다.
const path = require('path');
const { inspect } = require('../src/utils/profanity');

let bad = 0;
const ok = (name, got, want) => {
  const pass = JSON.stringify(got) === JSON.stringify(want);
  if (!pass) bad += 1;
  console.log((pass ? 'OK   ' : 'FAIL ') + name + ' → ' + JSON.stringify(got)
    + (pass ? '' : ' (기대: ' + JSON.stringify(want) + ')'));
};

// ── 만들어 내는 말뭉치 ──
const 때 = ['새벽 5시', '아침 7시', '오전 10시', '점심 12시', '오후 3시', '저녁 6시', '밤 9시',
  '한시', '두시', '세시', '네시', '다섯시', '열두시', '3시', '4시', '7시', '11시'];
const 부위 = ['발목', '발바닥', '발', '팔', '팔꿈치', '팔뚝', '어깨', '허리', '무릎', '종아리',
  '가슴', '등', '복근', '이두', '삼두', '광배', '햄스트링', '대퇴', '손목', '목'];
const 말끝 = ['이 아파요', '운동했어요', '부터 했어요', '이 안 들어가요', '기록이 사라져요',
  '을 다쳤어요', '이 시큰해요', '운동 기록을 적었어요'];
const 운동 = ['인클라인 덤벨프레스', '스미스머신 스쿼트', '루마니안 데드리프트', '랫풀다운',
  '케이블 크로스오버', '시티드 로우', '고블릿 스쿼트', '풀업 바 지지대', '벤치프레스',
  '클로즈그립 벤치프레스', '다이아몬드 푸시업', '사이드 레터럴 레이즈'];
const 무게 = ['48kg', '50kg', '12.5kg', '100kg', '맨몸', '밴드'];
const 흔한말 = [
  '3개년 계획으로 하고 있어요', '시발점에서 다시 시작했어요', '시발역 근처예요',
  '보지도 못했어요', '씹어 먹듯이 천천히 했어요', '자지 않고 운동했어요',
  '화면이 꺼져요', '기록을 뒤져봐도 안 나와요', '죽어라 눌러도 저장이 안 돼요',
  '사부작사부작 적고 있어요', '48번 눌렀어요', '구부정한 자세를 고치고 싶어요',
  '미니미 라는 닉네임을 쓰고 싶어요', '어머니미소 라는 이름이 안 돼요',
  '바쁘신데 죄송해요', '한 세트가 저절로 사라져요', '네 번이나 다시 깔았어요',
];

const 말뭉치 = [];
for (const t of 때) for (const b of 부위) for (const e of 말끝) 말뭉치.push(`${t} ${b}${e}`);
for (const x of 운동) for (const w of 무게) 말뭉치.push(`${x} ${w} 3세트 했어요`);
말뭉치.push(...흔한말);

console.log(`── 멀쩡한 말 ${말뭉치.length.toLocaleString()} 개 ──`);
const 걸린것 = [];
for (const s of 말뭉치) {
  const r = inspect(s);
  if (r.level !== 'clean') 걸린것.push({ s, level: r.level, hits: r.hits });
}
ok('하나도 안 걸린다', 걸린것.length, 0);
for (const c of 걸린것.slice(0, 10)) {
  console.log(`   ${c.level} ${JSON.stringify(c.s)} ← ${c.hits.join(', ')}`);
}
if (걸린것.length > 10) console.log(`   … 그리고 ${걸린것.length - 10} 개 더`);

console.log('\n── 그래도 진짜 욕은 걸려야 한다 ──');
const 욕 = {
  severe: ['씨발', '시발 왜 안 되냐', '씨 발', '시1발', 'ㅅㅂ', 'ㅆㅂ', 'ㅈㄹ',
    '개새끼', '좆같네', '지랄하네', 'fuck this app', '염병할'],
  hate: ['병신같은 앱', '느금마', '애미없는', '한남충', '김치녀', '짱깨', '틀딱'],
  mild: ['짜증나요', '개같은 화면', '빡쳐요', '젠장', '미친 버그'],
};
for (const [want, list] of Object.entries(욕)) {
  const 틀린것 = list.filter((s) => inspect(s).level !== want);
  ok(`${want} 가 ${want} 로 걸린다 (${list.length}개)`, 틀린것, []);
}

console.log('\n── 고친 자리가 되살아나지 않는가 ──');
// 시각을 걷는 것은 **시각일 때만** 이어야 한다. 「시발」 자체는 그대로 걸려야 한다
ok('「시발」은 그대로 걸린다', inspect('시발').level, 'severe');
ok('「3시 발목」은 안 걸린다', inspect('3시 발목이 아파요').level, 'clean');
ok('「시발점」도 안 걸린다 (始發點)', inspect('시발점에서 시작').level, 'clean');
ok('「니미럴」은 그대로 걸린다', inspect('니미럴 왜 안 되냐').level, 'severe');
ok('「미니미」는 안 걸린다', inspect('미니미').level, 'clean');

console.log('\n' + (bad ? bad + '건 실패' : '전부 통과'));
process.exit(bad ? 1 : 0);
