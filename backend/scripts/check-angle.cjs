// **거절 문구가 가리키는 길이 실제로 통하는가** (2026-11-17)
//
//   npm run angle
//   node scripts/check-angle.cjs --되돌려     일부러 어긋낸 꼴 일곱을 먹여 본다
//
// ── 왜 이 자가 생겼나 ──
//
// 11/17 에 「이름이 조용히 잘리는 것」을 거절로 바꿨다(`tagLike` · `ANGLE_WHY`,
// 주인 결정: 「거절하고 까닭을 말한다」). 그 까닭은 이렇게 말한다 —
//
//     꺾쇠 뒤에 글자를 붙여 쓸 수 없어요 — 「L < R」 처럼 띄어 주세요
//
// **그런데 「L < R」 도 거절됐다.** 식이 `/<\s*[/!?a-zA-Z]/` 여서 `<` 와 글자 사이의
// 공백을 넘어가 매치했다. 안내대로 고쳐 넣은 사람이 **또 막힌다** — 빠져나갈 길이
// 없는 꼴이고, 주인이 고른 「까닭을 말한다」는 **그 까닭이 가리키는 길이 통할 때만**
// 지켜진다. 걷는 식(`TAG`)도 같은 `\s*` 를 들고 있어서 `L < R` 이 **「L」로 잘렸다.**
//
// 띄어 쓴 것을 걸 이유도 없다 — HTML 파서는 `<` **바로 뒤**에 ASCII 글자가 와야
// tag open 으로 읽는다. `< a` 는 그냥 글자다.
//
// ── 무엇을 보는가 ──
//
//   ⑴ **문구에 적힌 보기를 문구에서 뽑아** 그것이 통하는지 본다. 보기를 여기 베껴
//      적지 않는다 — 베끼면 문구를 고치는 날 **자만 옛 보기를 본다**(「자가 지금을
//      베끼면 거짓이 된다」류)
//   ⑵ 붙여 쓴 것은 **거절**한다 (그것이 이 고침의 뜻이다)
//   ⑶ 11/03 의 선이 그대로 산다 — 홀로 쓰인 꺾쇠(`60>65` · `< 45도` · `3 <- 4`)와
//      `&` · `'` 는 **지우지도 거절하지도 않는다**
//   ⑷ **거절하지 않는 것은 걷지도 않는다** — 거절 안 하기로 한 값이 조용히 잘리면
//      11/03 에 막은 그 자리로 돌아간다
const path = require('path');

const S = require(path.join(__dirname, '..', 'src', 'utils', 'sanitize'));
let bad = 0;
const ok = (name, got, want) => {
  const pass = JSON.stringify(got) === JSON.stringify(want);
  if (!pass) bad += 1;
  console.log((pass ? 'OK   ' : 'FAIL ') + name + ' → ' + JSON.stringify(got)
    + (pass ? '' : ' (기대: ' + JSON.stringify(want) + ')'));
};

// ── 식은 한 자리에 둔다 — 되돌려-FAIL 이 **같은 것**을 부른다 ──
const 식 = {
  // 문구 속 「…」 안의 보기를 뽑는다 — `「L < R」 처럼 띄어 주세요`
  문구속보기: (why) => {
    const m = /「([^」]+)」/.exec(String(why || ''));
    return m ? m[1] : '';
  },
  걸리나: (v) => S.tagLike(v),
  이름으로남나: (v) => S.cleanName(v, 100),
  긴글로남나: (v) => S.sanitizeMultiline(v),
};

console.log('── 1. 문구가 가리키는 길이 통하는가 ──');
const 보기 = 식.문구속보기(S.ANGLE_WHY);
ok('거절 문구에서 보기를 뽑았다 (못 뽑으면 자가 아무것도 안 본 것이다)', 보기.length > 0, true);
console.log('       문구: ' + S.ANGLE_WHY);
console.log('       보기: ' + JSON.stringify(보기));
// ★ 이 자의 핵 — **안내대로 적은 값이 통해야 한다**
ok('★ 문구가 적어준 보기는 **거절되지 않는다**', 식.걸리나(보기), false);
ok('  그 보기가 이름으로 **그대로** 남는다', 식.이름으로남나(보기), 보기);
ok('  긴 글에서도 그대로 남는다', 식.긴글로남나(보기), 보기);

console.log('');
console.log('── 2. 붙여 쓴 것은 거절한다 (이 고침의 뜻) ──');
ok('붙여 쓴 꺾쇠는 걸린다', ['L<R', 'a<b 스쿼트', '덤벨 L<R'].filter((v) => !식.걸리나(v)), []);
ok('  태그 꼴도 걸린다', ['<script>x</script>', '</div>', '<!--x', '<?php'].filter((v) => !식.걸리나(v)), []);

console.log('');
console.log('── 3. 11/03 의 선이 그대로 사는가 ──');
// 홀로 쓰인 꺾쇠 · `&` · `'` 는 사람이 적은 글이다. 지우면 **뜻이 바뀐다**
const 그대로 = ['무게 60>65', '허리 각도 < 45도', '3 <- 4', '벤치 & 스쿼트', "don't", '<3', '5<10'];
ok('홀로 쓰인 꺾쇠 · & · 따옴표는 안 걸린다', 그대로.filter((v) => 식.걸리나(v)), []);
ok('  이름으로도 그대로 남는다', 그대로.filter((v) => 식.이름으로남나(v) !== v), []);
ok('  긴 글로도 그대로 남는다', 그대로.filter((v) => 식.긴글로남나(v) !== v), []);

console.log('');
console.log('── 4. 거절하지 않는 것은 걷지도 않는가 ──');
// 거절 안 하기로 한 값이 **조용히 잘리면** 11/03 에 막은 자리로 돌아간다.
// 거절하는 값(`L<R`)은 여기서 안 본다 — 그것은 라우트가 막으므로 걷기까지 안 온다
const 안거절 = [...그대로, 보기].filter((v) => !식.걸리나(v));
ok('거절 안 하는 값이 이름에서 안 잘린다', 안거절.filter((v) => 식.이름으로남나(v) !== v), []);
ok('  긴 글에서도 안 잘린다', 안거절.filter((v) => 식.긴글로남나(v) !== v), []);

if (process.argv.includes('--되돌려')) {
  console.log('');
  console.log('── 되돌려-FAIL: 일부러 어긋낸 꼴을 먹인다 ──');
  let 샌것 = 0;
  // 옛 식(`\s*` 가 있던 것)을 그 자리에서 되살려 **같은 질문**을 먹인다
  const 옛걸리나 = (v) => /<\s*[/!?a-zA-Z]/.test(v);
  const 꼴 = [
    ['옛 식(`\\s*`)은 문구의 보기를 거절한다', () => 옛걸리나(보기), true],
    ['  그래서 안내대로 적어도 또 막힌다', () => 옛걸리나('L < R'), true],
    ['옛 식은 붙여 쓴 것도 거절한다 (그쪽은 맞았다)', () => 옛걸리나('L<R'), true],
    ['지금 식은 띄운 것을 안 걸고 붙인 것만 건다',
      () => [식.걸리나('L < R'), 식.걸리나('L<R')], [false, true]],
    ['문구에서 보기를 못 뽑으면 빈 글자다 (자가 조용해지지 않게)',
      () => 식.문구속보기('까닭만 적고 보기가 없는 글'), ''],
    // 거짓 FAIL 막이 — 11/03 의 선을 거절로 바꾸면 안 된다
    ['`무게 60>65` 를 거절하면 11/03 의 선이 깨진다 (안 걸려야 한다)',
      () => 식.걸리나('무게 60>65'), false],
    ['`<3` 도 안 걸린다 (숫자는 태그가 아니다)', () => 식.걸리나('<3'), false],
  ];
  for (const [이름, 부르기, 어긋난값] of 꼴) {
    const 받은것 = 부르기();
    const 집었다 = JSON.stringify(받은것) === JSON.stringify(어긋난값);
    if (!집었다) 샌것 += 1;
    console.log((집었다 ? 'OK   잡는다: ' : 'FAIL 샌다  : ') + 이름
      + ' → ' + JSON.stringify(받은것)
      + (집었다 ? '' : ' (기대: ' + JSON.stringify(어긋난값) + ')'));
  }
  bad += 샌것;
  console.log(샌것 ? '  ↑ **어긋난 꼴을 자가 못 집었다.** 식이 느슨하다'
    : '  어긋낸 꼴 ' + 꼴.length + '개를 다 집었다');
}

console.log('\n' + (bad ? bad + '건 실패' : '전부 통과'));
process.exit(bad ? 1 : 0);
