/** 아는 꼴인가 — 맞는 첫 줄을 돌려준다 (없으면 `null`) */
function matchRule(detail) {
  const text = String(detail || '');
  for (const r of RULES) if (r.꼴.test(text)) return r;
  return null;
}

/**
 * 모르는 꼴에도 **말은 한다.** 아는 것이 없을 때 「모르겠다」로 끝내면 그 오류는
 * 영영 안 고쳐진다 — 오류 이름과 적힌 자리만으로 할 수 있는 말을 적는다
 */
function fallback(detail) {
  const name = (String(detail).match(/· ([A-Za-z]*Error): /) || [])[1] || 'Error';
  return {
    갈래: `아직 모르는 꼴 (${name})`,
    급함: 2,
    까닭: '이 표에 없는 오류다 — 적힌 `파일:줄` 이 유일한 실마리다',
    볼곳: '아래 「그 줄」에 찍힌 코드',
    다음: '그 자리를 읽고 **까닭을 알아낸 뒤 `agents/buchongjae/rules.js` 에 한 줄 더한다** '
      + '— 그래야 다음에 같은 꼴을 바로 안다',
    사람: '모른다 — 그 길을 눌러 봐야 안다',
    모름: true,
  };
}

module.exports = { RULES, matchRule, fallback };
