/**
 * 아는 꼴인가 — 맞는 첫 줄을 돌려준다 (없으면 `null`)
 *
 * `출처` 는 `'서버'`(기본) 또는 `'화면'` 이다 (2026-11-26 · 맵시).
 *   · 화면 기록이면 **화면 줄을 먼저** 맞대고, 없으면 일반 줄로 내려간다
 *     (`Cannot read propert…` 처럼 양쪽에서 나는 꼴이 있다). 그때 **담당은 맵시**다
 *   · 서버 기록에는 화면 줄을 맞대지 않는다 — 「새로고침하면 낫는다」가 거짓이 된다
 */
function matchRule(detail, 출처) {
  const text = String(detail || '');
  const 화면 = 출처 === '화면';
  const 줄들 = 화면
    ? [...RULES.filter((r) => r.출처 === '화면'), ...RULES.filter((r) => !r.출처)]
    : RULES.filter((r) => !r.출처);
  for (const r of 줄들) {
    if (!r.꼴.test(text)) continue;
    // 화면에서 난 것은 담당이 맵시다 — 일반 줄로 맞았어도 **볼 곳은 화면 쪽**이다
    return 화면 && !r.담당 ? Object.assign({}, r, { 담당: '맵시' }) : r;
  }
  return null;
}

/**
 * 모르는 꼴에도 **말은 한다.** 아는 것이 없을 때 「모르겠다」로 끝내면 그 오류는
 * 영영 안 고쳐진다 — 오류 이름과 적힌 자리만으로 할 수 있는 말을 적는다
 */
function fallback(detail) {
  const name = (String(detail).match(/· ([A-Za-z]*Error): /) || [])[1] || 'Error';
  return {
    갈래: `아직 모르는 꼴 (${name})`,
    급함: 2,
    까닭: '이 표에 없는 오류다 — 적힌 `파일:줄` 이 유일한 실마리다',
    볼곳: '아래 「그 줄」에 찍힌 코드',
    다음: '그 자리를 읽고 **까닭을 알아낸 뒤 `agents/buchongjae/rules.js` 에 한 줄 더한다** '
      + '— 그래야 다음에 같은 꼴을 바로 안다',
    사람: '모른다 — 그 길을 눌러 봐야 안다',
    모름: true,
  };
}

module.exports = { RULES, matchRule, fallback };
