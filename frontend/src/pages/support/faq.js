// 며칠을 기다리고, 답하는 쪽은 같은 답을 또 쓴다.
//
// topic 은 바로 누를 수 있는 짧은 이름이다 — 무엇을 쳐야 할지 모르는 사람이 대부분이다.
// keywords 는 검색에만 쓴다. 사람들이 실제로 칠 법한 말을 넣는다 — 화면에 적힌 단어와
// 물어볼 때 쓰는 단어는 다르다 ('정지' 를 '차단' · '막혔' 으로 친다).

