// 공백·기호를 지우고 소문자로. '초 월' 도 '초월' 로 친다
const norm = (s) => String(s || '').toLowerCase().replace(/[\s.,!?~·・\-_'"]/g, '');

/**
 * 친 글자로 자주 묻는 것을 찾는다.
 *
 * 두 글자부터 찾기 시작한다 — 한 글자로 찾으면 거의 모든 항목이 걸려서
 * 아무 도움이 안 되고, 치는 동안 목록이 요동친다.
 *
 * 점수는 어디서 맞았는지로 매긴다. 질문에 맞은 것이 답에 스친 것보다 위다.
 */
export function matchFaq(query, limit = 3) {
  const q = norm(query);
  if (q.length < 2) return [];

  return FAQ
    .map(item => {
      const inQ = norm(item.q).includes(q);
      const inKeyword = (item.keywords || []).some(k => {
        const nk = norm(k);
        // 짧은 키워드는 서로를 포함하는지 양쪽으로 본다 ('렙' ↔ '레벨업')
        return nk.includes(q) || q.includes(nk);
      });
      const inA = norm(item.a).includes(q);
      const score = (inQ ? 3 : 0) + (inKeyword ? 2 : 0) + (inA ? 1 : 0);
      return { item, score };
    })
    .filter(r => r.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(r => r.item);
}
