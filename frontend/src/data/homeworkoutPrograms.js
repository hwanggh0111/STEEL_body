// 어떤 운동이 무엇을 쓰는가. 이름에 그 물건이 안 적힌 것들(데드행 · 월싯 · 노르딕 컬)이
// 있어서 이름만 훑어서는 안 된다 — 짝을 하나씩 적는다
const GEAR_RULES = [
  { match: /의자|스텝업/, item: '의자' },
  { match: /식탁/, item: '식탁 (튼튼한 것)' },
  { match: /수건/, item: '수건' },
  { match: /배낭/, item: '배낭 (책 3~4권이나 2L 물통 둘)' },
  { match: /데드행/, item: '문틀바 (없으면 수건)' },
  { match: /월 |월싯/, item: '벽' },
  { match: /노르딕/, item: '발 끼울 곳 (소파 · 침대 아래)' },
];

/** 그 프로그램에 필요한 것. 아무것도 안 쓰면 빈 배열 — 화면이 「맨몸만」이라고 적는다 */
export function gearOf(name) {
  const exs = PROGRAMS[name] || [];
  const found = [];
  for (const rule of GEAR_RULES) {
    if (exs.some((e) => rule.match.test(e.name)) && !found.includes(rule.item)) found.push(rule.item);
  }
  return found;
}

