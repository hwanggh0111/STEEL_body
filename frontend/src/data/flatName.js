// **운동 이름을 눕히는 식 — 한 자리** (2026-11-19 · 정석 2차 지적)
//
// ── 왜 생겼나 ──
//
// 같은 식이 **네 벌**이 되어 가고 있었다 — `plateMath.js` · `restPerExercise.js` ·
// `altExercise.js` · `pace.js`. 글자까지 똑같았지만, 머리글마다 스스로 「**두 식이
// 갈리면 열쇠가 안 맞는다**」고 적어두고 **갈릴 수 있게** 둔 꼴이었다.
//
// 이 저장소가 거듭 없애온 그 모양이다 — 한쪽에서 「·」 하나를 더 지우게 고치면
// 그날부터 **같은 운동이 다른 것으로 보인다**: 쉬는 시간은 「벤치 프레스」에 기억해
// 뒀는데 원판은 「벤치프레스」로 찾는다. 그리고 그것은 **아무 자도 안 울린다.**
//
// ── 무엇을 지우나 ──
//
// 사람이 같은 운동을 적는 **여러 꼴**을 하나로 모은다 — 대소문자 · 공백(가운데 것까지) ·
// 점 · 쉼표 · 물음표 · 느낌표 · 물결 · 가운뎃점 · 붙임표 · 밑줄 · 따옴표 · 괄호.
// 「벤치 프레스」 · 「벤치프레스」 · 「Bench Press」 · 「벤치-프레스」가 모두 한 열쇠가 된다.
//
// **한글 자모는 안 건드린다** — 「ㅅㅋㅇㅌ」처럼 적는 사람은 없고, 건드리면 겹받침이
// 깨진다.

/** 눕힌 이름. **이 앱에서 운동 이름을 견주는 식은 이것 하나다** */
export const flatName = (s) => String(s || '')
  .toLowerCase()
  .replace(/[\s.,!?~·・\-_'"()]/g, '');

/**
 * **두 이름이 같은 운동인가.** 눕혀 견준다.
 *
 * ── 왜 이 손이 생겼나 ── (2026-11-27 · 정석, 벼림 넘김의 뿌리)
 *
 * 위 머리글이 「견주는 식은 이것 하나다」라고 못 박았는데, **견주는 자리마다
 * 제 손으로 짜고 있었다** — 열세 자리였다. 꼴이 셋이나 돌아다녔다:
 *
 *   `String(w?.exercise ?? "").trim() === name`      ← 글자 그대로 (열한 자리)
 *   `String(a||"").trim().toLowerCase() === …`        ← 대소문자만 (`nextSet.js`)
 *   `flatName(a) === flatName(b)`                     ← 맞는 식 (`gymSetting.js`)
 *
 * 그래서 이 머리글이 예고한 그대로 됐다 — **쉬는 시간은 「벤치 프레스」에 기억해
 * 뒀는데 지난 세트는 「벤치프레스」로 찾는다.** 운동 이름은 홈 · 검색 · 루틴에서
 * **자유 글자**로 들어오므로(사전을 안 거친다) 한 사람이 두 꼴을 섞어 적는 일이
 * 흔하다. 눕히는 식을 한 자리에 둬도 **견주는 손이 없으면** 또 갈린다.
 *
 * **빈 이름은 아무와도 같지 않다** — `!!x` 로 막는다. 빈 열쇠를 「다 맞음」으로
 * 두면 이름을 못 읽은 줄이 **모든 운동의 지난 기록**으로 끼어든다.
 *
 * 번역은 하지 않는다 — 「Bench Press」와 「벤치프레스」는 **다른 글자**다
 * (묶으려면 이름 사전을 들여야 하고, 그러면 사전에 없는 이름이 또 갈린다).
 */
export const sameName = (a, b) => {
  const x = flatName(a);
  return !!x && x === flatName(b);
};
