// 로그인 화면에 적어두는 아이디 — 아이디를 바꿨을 때 어떻게 되나 (2026-10-02).
//
// 로그인 화면은 **마지막에 친 것**을 다음에 채워준다(`saved_id`). 그 칸은 아이디도
// 메일도 받으므로, 적혀 있는 값이 둘 중 무엇인지는 **그 사람이 무엇으로 들어왔는지**에
// 달려 있다.
//
// 아이디를 바꾸면 그 값이 **옛 아이디로 남는다.** 바꾼 사람이 제일 먼저 하는 일이
// 로그아웃인데, 그러면 자동으로 채워진 그 아이디로는 **로그인이 안 된다** — 옛 아이디는
// 그 자리에서 못 쓰게 되기 때문이다(`PUT /auth/username`). 「방금 바꿨는데 왜 안 되지」가
// 되고, 사람은 아이디를 바꾼 것과 로그인이 안 되는 것을 잇지 못한다.
//
// ── 메일을 적어둔 사람은 건드리지 않는다 ──
//
// 메일로 들어오는 사람의 `saved_id` 는 메일이고, 그건 아이디를 바꿔도 그대로 통한다.
// 「아이디를 바꿨으니 `saved_id` 도 새 아이디로」 하고 덮으면, 메일로 들어오던 사람이
// 갑자기 아이디로 들어가게 된다 — 고쳐준 게 아니라 바꿔버린 것이다.
//
// 이 파일은 화면도 저장소도 모른다. 적혀 있던 값과 아이디 둘을 받는다 —
// `npm run savedid` 가 값으로 본다.

/** 아이디를 하나의 말로 맞춘다. 서버의 `usernameKey` 와 같은 규칙이다. */
const key = (v) => String(v ?? '').trim().toLowerCase();

/**
 * 아이디를 바꾼 뒤 `saved_id` 에 무엇을 둘 것인가.
 *
 * saved  지금 적혀 있는 값 (아이디일 수도, 메일일 수도, 없을 수도)
 * was    바꾸기 전 아이디
 * now    바꾼 뒤 아이디
 *
 * 돌려주는 것: **새로 적을 값**, 또는 `null`(건드리지 않는다).
 * `null` 을 돌려줄 때 호출하는 쪽은 **아무것도 쓰지 않는다** — 빈 값을 쓰면
 * 적어둔 것이 지워져, 다음 로그인에서 칸이 비어 있다.
 */
export function nextSavedId(saved, was, now) {
  const w = key(was);
  const n = key(now);
  // 바꾸기 전 아이디를 모르면 무엇을 고쳐야 할지도 모른다
  if (!w || !n) return null;
  // 적어둔 것이 없으면 새로 만들지 않는다 — 적어둔 적 없는 사람에게
  // 아이디를 채워주면 그 칸이 저절로 생긴 것처럼 보인다
  if (!key(saved)) return null;
  // 적어둔 것이 **그 옛 아이디일 때만** 고친다 (메일이면 여기서 끝난다)
  if (key(saved) !== w) return null;
  return now;
}
