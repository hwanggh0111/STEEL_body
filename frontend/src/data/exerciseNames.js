// **적힌 이름들을 묶어 고르는 목록을 만든다** (2026-11-27 · 맵시)
//
// ── 왜 생겼나 ──
//
// 기록 화면의 운동 필터가 이름을 **글자 그대로** 모았다. 운동 이름은 홈 · 검색 ·
// 루틴에서 **자유 글자**로 들어오니 「벤치 프레스」와 「벤치프레스」를 둘 다 적은
// 사람이 생긴다 — 고르는 칸에 **같은 운동이 두 줄**로 뜨고, 어느 쪽을 골라도 그
// 글자와 똑같은 줄만 걸러져 **절반만** 보였다.
//
// 견주는 식은 `flatName` 하나다(그 파일 머리글). 여기서는 그 식으로 **묶고**,
// 묶은 것에 **보일 이름 하나**를 고른다.
//
// ── 어느 글자를 보이나 (꼴 판단 · 맵시) ──
//
//   ⑴ **가장 많이 적은 꼴**
//   ⑵ 같으면 **가장 최근에 적은 꼴**
//   ⑶ 그래도 같으면 글자 순
//
// 「최근 것」을 먼저 두지 **않았다.** 마지막 한 번을 오타로 적으면(「벤치프레스ㅇ」)
// 목록에 뜨는 이름이 **그 오타로 바뀐다.** 목록에서 찾는 사람은 **자기가 익숙한
// 이름**을 찾고, 익숙한 것은 많이 적은 쪽이다. 글자 순을 마지막에 둔 것은 **같은
// 입력에서 늘 같은 답**이 나오게 하려는 것이다(안 그러면 다시 그릴 때마다 바뀐다).
//
// 「2가지 표기」 같은 꼬리말은 **안 붙인다** — 사람은 그것을 같은 운동으로 여기고
// 적었고, 몇 가지 꼴로 적혔는지는 앱의 사정이다.

import { flatName } from './flatName';

/**
 * 날짜별 기록 꾸러미에서 **고를 수 있는 운동 이름**을 만든다.
 *
 * @param {Record<string, Array<{exercise?: string}>>} byDate  날짜 → 그날 줄들
 * @returns {string[]} 보일 이름들 (글자 순)
 *
 * 날짜는 `YYYY-MM-DD` 라 **글자로 견줘도 시간 순**이다 — `Date` 로 바꾸지 않는다
 * (시간대 때문에 하루가 밀리는 자리를 이 저장소가 여러 번 고쳤다).
 */
export function pickExerciseNames(byDate) {
  const 묶음 = new Map();            // 눕힌 열쇠 → (적은 글자 → { 번, 끝 })
  for (const [날, 줄들] of Object.entries(byDate || {})) {
    for (const w of 줄들 || []) {
      const 열쇠 = flatName(w && w.exercise);
      if (!열쇠) continue;
      let 꼴들 = 묶음.get(열쇠);
      if (!꼴들) { 꼴들 = new Map(); 묶음.set(열쇠, 꼴들); }
      const 것 = 꼴들.get(w.exercise) || { 번: 0, 끝: '' };
      것.번 += 1;
      if (String(날) > 것.끝) 것.끝 = String(날);
      꼴들.set(w.exercise, 것);
    }
  }
  return [...묶음.values()]
    .map((꼴들) => [...꼴들.entries()].sort(
      (a, b) => b[1].번 - a[1].번
        || String(b[1].끝).localeCompare(String(a[1].끝))
        || a[0].localeCompare(b[0]),
    )[0][0])
    .sort((a, b) => a.localeCompare(b));
}

/** 고른 이름으로 줄을 거른다 — **눕혀** 견준다 (글자 그대로면 다르게 적은 날이 빠진다) */
export const matchesExercise = (줄, 고른이름) => {
  const 열쇠 = flatName(고른이름);
  return !열쇠 || flatName(줄 && 줄.exercise) === 열쇠;
};
