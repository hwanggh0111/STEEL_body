// 로그인·가입이 끝나고 **어디로 보낼 것인가** (2026-10-20).
//
// ── 왜 한 곳에 뒀나 ──
//
// `PrivateRoute` 는 못 들어간 자리를 `state.from` 에 담아두고 로그인 화면으로 보낸다.
// 로그인 화면은 그걸 받아 **가려던 자리로** 데려간다 — 거기까지는 9월부터 돼 있었다.
//
// 그런데 **가입은 그 값을 아예 안 봤다.** 그래서 이런 일이 생긴다 —
//
//   홈페이지에서 「가입하고 열기 — 「몸 지도」 화면」을 누른다
//   → 로그인 화면(from=/map) → 「회원가입」을 누른다 (**여기서 from 이 사라진다**)
//   → 가입을 끝낸다 → **「오늘」로 간다.** 몸 지도를 보러 온 사람인데
//
// 홈페이지에 **「가입하고 열기」라고 적어둔 10/20** 부터는 그게 그냥 어긋난 말이 아니라
// **거짓말**이다. 그래서 가입도 같은 값을 보게 했고, 거르는 규칙을 **한 곳에 뒀다** —
// 로그인·가입 두 곳에 같은 규칙을 적으면 한쪽만 고쳐지는 날이 온다.
//
// ── 왜 거르나 (오픈 리다이렉트) ──
//
// 이 값은 **주소로도 들어올 수 있다**(누가 링크를 만들어 보낼 수 있다). 그대로 믿고
// `navigate` 에 넘기면 `//남의사이트.com` 같은 것을 넣어 **로그인 직후 딴 데로
// 보내버리는 길**이 된다. `/` 로 시작하되 `//` 도 `/\` 도 아닌 것만 통과시킨다.
//
// 로그인·가입으로 되돌리는 것도 막는다 — 그 자리를 맴돈다.

/** 들어온 자리로 보내도 되는지. 아니면 빈 글자를 돌려준다. */
export function safeBackTo(value) {
  const to = typeof value === 'string' ? value : '';
  if (!to.startsWith('/') || to.startsWith('//') || to.startsWith('/\\')) return '';
  if (to.startsWith('/login') || to.startsWith('/register')) return '';
  return to;
}

/** 로그인·가입이 끝난 뒤 갈 자리. 들고 온 것이 없으면 「오늘」이다. */
export function afterAuthPath(value) {
  return safeBackTo(value) || '/home';
}
