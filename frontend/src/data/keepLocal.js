// **기기에만 남는 값을 담는다 — 못 담으면 한 번 말한다** (2026-10-31).
//
// ── 왜 ──
//
// `saveLS` 는 못 담으면 터지지 않고 `false` 를 준다(8월에 그렇게 고쳤다 — 던진
// 자리가 모듈 맨 위면 앱이 흰 화면이 된다). 그 값을 **안 보는 자리가 여럿이었다.**
//
// 담아두면 좋은 값(검색 기록 · 고른 바 무게 · 만든 소리)은 조용히 잃어도 된다 —
// 그 자리들은 주석에 그렇게 적어뒀다. 문제는 **그 사람이 적은 것이 기기에만 있고,
// 그것이 앱의 말을 바꾸는 자리**다 —
//
//   · 앱 잠금 — 담기지 않으면 **안 걸렸는데 걸렸다고 믿는다** (10/31 에 고쳤다)
//   · 체형 이력 — 담기지 않으면 **다시 열었을 때 「지난 번」이 없다** (10/31)
//   · 아픈 곳 — 담기지 않으면 **아픈 부위를 또 추천한다**
//
// 10/27 ⑯ 이 그 꼴이었다: 쿠키를 막아둔 브라우저에서 휴식 알림을 한 번도 안 물었고
// **기능이 조용히 없는 것이 됐다.**
//
// ── 어떻게 ──
//
// **한 번만 말한다.** 못 담는 브라우저에서는 **누를 때마다** 실패하므로, 자리마다
// 토스트를 띄우면 쓰는 것을 막는 잔소리가 된다. 한 판에 한 번, **무엇이 안 남는지**를
// 적어 말한다. 그 뒤로는 화면이 제 자리에서 적는다(체형 화면이 그렇게 한다).
import { saveLS } from './safeStorage';
import { toast } from '../components/Toast';
import { eul } from './particle';

/** 이 판에 이미 말했나. 새로고침하면 다시 한 번 말한다 */
let 말했다 = false;

/**
 * 담고, 못 담았으면 **무엇이 안 남는지** 한 번 말한다.
 *
 * @param {string} key   `data/localKeys.js` 의 이름
 * @param {string} value 담을 글자
 * @param {string} what  안 남는 것의 이름 — 「아픈 곳」 · 「하던 자리」
 * @returns {boolean} 담겼나 — 부르는 쪽이 제 자리에 적을 수 있다
 */
export function keepLocal(key, value, what) {
  if (saveLS(key, value)) return true;
  if (!말했다) {
    말했다 = true;
    // **보간 뒤에 조사를 글자로 박지 않는다** (`npm run data` 가 잡는다) —
    // 「아픈 곳을」 · 「하던 자리를」 처럼 받침이 갈린다. 조사는 자를 쓴다
    toast(`이 브라우저가 저장을 막아 ${eul(what)} 기억하지 못해요 — 사이트 데이터 저장을 켜주세요`, 'error');
  }
  return false;
}
