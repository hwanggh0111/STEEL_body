// 사람이 **치고 붙여넣는 칸**을 다듬는 자 (2026-11-03).
//
// ── 무엇에 걸렸나 ──
//
// 사용자 자리에 앉아 가입을 해보다가, **앞뒤에 공백이 붙은 값**에서 막혔다.
//
//   이메일 칸에 ` kim@a.com ` → **「올바른 이메일 형식이 아니에요」**
//                               (형식 자가 `[^\s@]` 라 공백을 못 받는다)
//   아이디 칸에 ` kim12 `      → **「영문, 숫자, 특수문자(!@#$%^&*._-)만 가능」**
//
// 둘 다 **눈에는 멀쩡한 값**이다. 그런데 화면은 「형식이 틀렸다」·「쓸 수 없는
// 글자다」라고만 말하고, 사람은 보이지 않는 글자를 의심할 수 없다. 폰에서 주소를
// 붙여넣으면 공백·줄바꿈이 함께 오는 일은 흔하다(메일 앱에서 복사 · 자동완성 ·
// 비밀번호 관리자). **가입은 이 앱에서 제일 처음 만나는 화면**이라 더 나쁘다.
//
// ── 서버는 이미 다듬는다 ──
//
// `db.emailKey` 와 `usernameKey` 가 `trim().toLowerCase()` 로 맞추고
// (`routes/auth.js` 의 `loginKeyOf` 도 같다), 닉네임은 `cleanName` 이 다듬는다.
// 그래서 **로그인은 공백이 붙어도 들어간다** — 값으로 확인했다.
// 막히는 자리는 **들어오는 문 하나**였다: 화면이 제 손으로 보는 형식 검사.
//
// ── 그래서 칸에서 떼어낸다 ──
//
// 저장할 때 다듬는 것으로는 늦다. 화면이 **치는 동안** 판단해서 그 자리에 말을
// 띄우기 때문이다(「누르기 전에 말한다」 — 이 앱이 거듭 세워온 선). 칸이 받는
// 그 순간에 떼어내면 사람은 **애초에 그 말을 안 본다.**
//
// 이메일도 아이디도 **공백이 들어갈 수 없는 값**이라 안쪽까지 전부 지운다 —
// 붙여넣기에는 줄바꿈과 탭도 섞여 온다. 닉네임은 다르다(「근호 아빠」) → 앞뒤만.
//
// 한 자리에 둔다. 쓰는 데가 셋이다 — 가입 · 로그인 · 설정함의 아이디 바꾸기.

/** 메일 주소 칸. 공백·줄바꿈을 전부 떼고 소문자로 (서버가 맞추는 그 모양이다) */
export function cleanEmailField(v) {
  return String(v ?? '').replace(/\s+/g, '').toLowerCase();
}

/** 아이디 칸. 같은 규칙이다 — 아이디에 공백은 쓸 수 없다 */
export function cleanIdField(v) {
  return String(v ?? '').replace(/\s+/g, '').toLowerCase();
}

/** 이름(닉네임) 칸. **안쪽 공백은 뜻이 있다** — 앞뒤만 떼어낸다 */
export function cleanNameField(v) {
  return String(v ?? '').trim();
}
