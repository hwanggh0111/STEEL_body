// **무엇이 무엇을 덮는가** — 화면을 덮는 것들의 층을 한 자리에 적는다 (2026-11-17 · 맵시).
//
// ── 왜 이 파일이 생겼나 ──
//
// 정석이 넘긴 류를 UI 쪽에서 훑다가 나왔다 — 「같은 생김새가 두 화면에 복붙되고
// 한쪽만 고쳐진 자리」. 덮개가 **열넷**인데 층수를 저마다 손으로 적어 뒀고,
// 그래서 **다섯이 어긋나 있었다**:
//
//   ⑴ ★ **잠금이 탭바 아래였다.** `AppLock` 은 `9000` 이고 `TabBar` 는 `9999` 다.
//      `AppLock.jsx` 머리글은 「**탭바도 머리도 통째로 가려야 한다** — 반쯤 가리면
//      그 틈으로 오늘 한 운동과 몸 사진 미리보기가 보인다」라고 적어두고 있었는데,
//      실제로는 **탭바와 휴식 띠(`9998`)가 잠금 위에 떠 있었다.** 띠에는 지금 하는
//      종목 이름이 적혀 있고, 탭바는 **눌린다** — 잠근 채로 화면을 옮길 수 있었다.
//      잠금은 기록을 가리려고 있는 것인데 가리지 못했다
//   ⑵ **비밀번호 찾기 창만 `9999`** 였다(나머지 모달은 `99999`). 탭바와 **동점**이라
//      어느 쪽이 위인지는 **DOM 차례**가 정했다 — 설정에서 열면 본문이 탭바보다
//      앞에 있으니 **탭바가 어두운 덮개 위로 올라왔다**. 자리만 다르면 다르게
//      보이는 것이 제일 못 찾는 꼴이다
//   ⑶ **확인 창이 모달보다 아래였다**(`99998` < `99999`). 모달 안에서 확인 창을
//      부르는 날 **묻는 창이 뒤에 깔린다** — 지금 그 길이 닿지는 않지만, 모달이
//      확인 창을 부르는 것은 흔한 일이라 앞으로 올 자리였다
//   ⑷ **겹쳐 찍기 · 말로 적기**(둘 다 `aria-modal="true"`)가 `9996` 이라 **탭바 ·
//      휴식 띠 아래**였다 — 카메라를 띄운 채로 탭이 눌렸다
//   ⑸ **운동 끝 결산**(`.finish-sheet`)이 `9998` 로 **탭바 아래**였고, **토스트**는
//      `9999` 라 **모든 모달 아래**였다. 결산 주석이 「토스트(9999)보다 아래에 둔다 —
//      결산 위에서도 「저장했어요」가 보여야 한다」라고 적고 있었는데, 정작 모달
//      위에서는 그 말이 안 보였다. **주석과 숫자가 서로 다른 말을 하고 있었다**
//
// 「덮개 하나를 더 띄우면서 앞의 것을 베껴 숫자를 하나 고치는」 것으로는 이 다섯을
// 못 막는다. **차례를 뜻으로 적고 숫자는 여기서만 센다.**
//
// ── 차례의 뜻 ──
//
// 아래로 갈수록 위에 그려진다 —
//
//   뒤판 · 서랍 · 휴식띠 · 탭바       앱의 **껍데기**
//   결산                              루틴을 마치면 화면을 덮는 장
//   모달                              화면이 띄우는 창 (카메라 · 말로 적기까지)
//   잠금                              **껍데기와 창을 통째로** 가린다
//   확인창                            잠금보다 위다 — 잠금 화면의 「네 자리를
//                                     잊으셨나요」가 **눌려야** 한다
//   토스트                            덮개 위에서도 「저장했어요」는 보여야 한다
//   스플래시                          들어올 때 가장 위
//   막힘 · 점검                       앱을 아예 못 쓰는 자리 (제일 위)
//
// 100 단위로 띄워 둔다 — 사이에 하나 끼워야 할 날이 와도 **전부를 다시 안 센다.**
// ── ★ **잠금은 확인창·토스트보다도 위다** ── (2026-11-17 · 정석)
//
// 위 ⑴ 을 고치면서 **확인창(`100400`)과 토스트(`100500`)를 잠금(`100300`) 위에**
// 뒀다. 확인창을 위에 둔 까닭은 맞다 — 잠금의 「네 자리를 잊으셨나요」가 눌려야
// 한다. 그런데 그러면 **아무 확인창이나** 잠금 위가 된다.
//
// 재현: 확인창을 띄운 채 폰을 내려놓으면 잠금 시간이 지나 잠금이 뜨고, **그 확인창이
// 잠금 위에 그대로 남는다**(`AppLock` 은 뜰 때 다른 덮개를 안 닫는다). 그리고 그
// 확인창에는 **기록이 적혀 있다** —
//
//     RoutineNotes.jsx:83   "{메모 본문 앞머리}" 메모를 지울까요
//     GymPage.jsx:120       {헬스장}의 {운동 이름} 세팅을 지울까요
//     HistoryPage.jsx:154   {날짜} 메모를 지울까요
//
// **잠금이 가리려는 것이 바로 이것이다.** 탭바가 떠 있던 것보다 더 샌다 — 글이
// 보이는 데 그치지 않고 **「지울까요」 단추가 살아 있다**(잠근 채로 기록을 지울 수
// 있다). 토스트도 같은 자리다: **잠긴 화면에서 「저장했어요」가 보여야 할 일이 없다.**
//
// 그래서 **잠금을 그 둘 위로** 올리고, 잠금이 **제가 띄운** 확인창만 쓰는 층을
// 따로 둔다(`잠금확인창`). 가르는 것은 `confirmDialog(…, { 잠금위: true })` 다 —
// 층으로 가르지 않으면 「모든 확인창을 위로」와 「잠금은 다 덮는다」가 같은 숫자를
// 두고 다툰다. 그리고 **층만 고치면 뒤에 숨은 창에 포커스와 낭독기가 남으므로**,
// 잠금이 뜰 때 떠 있던 확인창은 `AppLock` 이 **취소로 닫는다.**
//
