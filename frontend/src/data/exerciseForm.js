// 괄호 안은 같은 동작을 **어디서 하느냐**일 뿐이다 — (좌) · (의자) · (식탁 아래).
// 자세 설명은 괄호 없는 이름으로 하나만 둔다 (홈트가 쓰는 이름들이 그렇다)
const base = (name) => String(name || '').replace(/\s*\([^)]*\)/g, '').trim();

/**
 * 그 운동을 어떻게 하는지. 없으면 `null` — **화면은 그때 단추를 아예 안 그린다.**
 * 빈 자리를 눌러보게 두면 고장으로 읽힌다.
 */
export function formOf(name) {
  return FORM[base(name)] || FORM[String(name || '').trim()] || null;
}

/** 자세 설명이 있는 운동 수. 검사가 「사전을 다 덮었는가」를 볼 때 쓴다 */
export const FORM_COUNT = Object.keys(FORM).length;
