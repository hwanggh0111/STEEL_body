// 사진 한도는 서버가 정한다 — backend/src/routes/photos.js 가 base64 길이 2MB 를 넘기면 거절한다.
// (JSON 파일 DB 를 통째로 메모리에 올리는 구조라 한도를 함부로 올릴 수 없다)
//
// 파일 크기로 재면 어긋난다. base64 는 원본보다 약 33% 커진다.
// 1.9MB 짜리 사진이 프론트 검사(2MB)를 통과한 뒤 서버에서 2.5MB 가 돼 거절당했다 —
// 사용자 입장에서는 2MB 이하 사진을 골랐는데 '너무 크다' 는 말을 들은 셈이다.
export const PHOTO_MAX_BASE64 = 2 * 1024 * 1024;

// ── ★ **한도 안이면 아예 안 줄이고 있었다** ── (2026-11-26 · 근호 용량 점검)
//
// 위 `PHOTO_MAX_BASE64` 는 **거절하는 선**이다. 그런데 줄이는 자(`shrinkImage`)가
// 그 선을 **「여기까지는 그냥 둔다」로** 쓰고 있었다 — 1.4MB 짜리를 고르면 **원본
// 그대로** 올라갔다.
//
// 그것이 용량의 뿌리다. 근호가 재 보니 **사진을 다 채운 사람 40~50명이면 무료
// 512MB 가 넘친다**(한 장짜리 JSON DB 를 통째로 메모리에 올리는 구조라 사진도 힙에
// 올라간다). 사람마다 3장 × 1.5MB 가 그 수다.
//
// 그런데 **화면에 그리는 크기는 긴 변 1280px 이면 넉넉하다**(`shrinkImage` 의
// `MAX_EDGE` — 몸 사진을 견주는 용도다). 1280px JPEG 은 대개 **200~400KB** 다.
// 즉 **쓰지도 않는 해상도를 사람마다 1MB 넘게** 들고 있었던 셈이다.
//
// 그래서 선을 둘로 가른다 —
//
//   `PHOTO_MAX_BASE64`    거절하는 선 (서버와 같은 2MB). **건드리지 않는다**
//   `PHOTO_TARGET_BASE64` **담아둘 선**. 이걸 넘으면 줄인다
//
// 500KB 로 둔다. 1280px 로 다시 구운 것이 그 안에 들고(200~400KB), 이미 작고 잘
// 눌린 그림은 **다시 굽지 않는다**(아래 `needsShrink` 가 긴 변도 같이 본다 —
// 작게 잘 눌린 그림을 다시 구우면 화질만 손해다).
export const PHOTO_TARGET_BASE64 = 500 * 1024;

// **원본 크기로 재는 값은 걷어냈다** (2026-09-30).
//
// `PHOTO_MAX_FILE`(base64 로 부풀어도 한도를 안 넘는 원본 크기)을 두고 「줄여도 안 되는
// 마지막 경우를 알리기 위해 남긴다」고 적어뒀는데, **쓰는 데가 한 곳도 없었다.**
// 그 안내는 실제로 `PHOTO_MAX_LABEL` 로 하고 있었다. 죽은 값을 두면 「원본 크기로도
// 거른다」고 믿게 된다 (오늘 횟수 세기의 `MIN_RANGE` 와 같은 자리다).

export const PHOTO_MAX_LABEL = '1.5MB';

// ── **거절하는 말은 한 자리에서 만든다** ── (2026-11-20)
//
// 사진을 거절하는 자리가 셋이다 — 프로필(`Layout`) · 전후 사진(`ComparePage`) ·
// 홈페이지 사진(`SitePhotoAdmin`). 셋이 **같은 말을 따로 적고 있었고**, 그래서
// 셋 다 **크기 탓으로만** 말했다. 그런데 거절되는 까닭은 둘이다 —
//
//   ⑴ 진짜로 크다 → 「줄여 오세요」가 맞는 말이고, 우리가 이미 줄여본 뒤다
//   ⑵ **못 읽었다**(데스크톱 크롬의 HEIC 등) → 줄여 와도 또 안 된다.
//      크기를 말하면 **사실이 아니고**, 할 수 있는 일도 안 알려주는 셈이다
//
// 말을 여기 한 자리에 둔다. 자가 세 자리에서 이 손을 부르는지 본다 —
// 베껴 적으면 한쪽만 고치는 날이 오고, 그날 나머지가 거짓을 말한다.
export function photoRejectMessage({ unreadable } = {}) {
  if (unreadable) {
    return '이 기기가 이 사진 형식을 못 읽어요 — 사진 앱에서 JPG 로 내보낸 뒤 다시 골라주세요';
  }
  return `사진은 ${PHOTO_MAX_LABEL} 이하만 가능해요`;
}
